package videos

import (
	"context"
	"errors"
	"io"
	"path"
	"strings"

	"github.com/shivamx64/streamix/internal/storage"
)

// MediaFile is an opened media object ready to be streamed to a client.
type MediaFile struct {
	Content     io.ReadCloser
	ContentType string
}

// OpenThumbnail opens the generated poster image for a completed video.
func (s *service) OpenThumbnail(
	ctx context.Context,
	userID string,
	videoID string,
) (*MediaFile, error) {

	video, err := s.GetByID(ctx, userID, videoID)
	if err != nil {
		return nil, err
	}

	if video.Status != StatusCompleted || video.ThumbnailKey == "" {
		return nil, ErrNotFound
	}

	return s.openMedia(ctx, video.ThumbnailKey)
}

// OpenHLS opens a file beneath the HLS output directory of a completed
// video. The requested path is relative to the directory containing the
// master playlist.
func (s *service) OpenHLS(
	ctx context.Context,
	userID string,
	videoID string,
	relativePath string,
) (*MediaFile, error) {

	video, err := s.GetByID(ctx, userID, videoID)
	if err != nil {
		return nil, err
	}

	if video.Status != StatusCompleted || video.HLSMasterKey == "" {
		return nil, ErrNotFound
	}

	cleanPath, ok := cleanMediaPath(relativePath)
	if !ok {
		return nil, ErrNotFound
	}

	hlsBase := path.Dir(video.HLSMasterKey)
	key := path.Join(hlsBase, cleanPath)

	if !strings.HasPrefix(key, hlsBase+"/") {
		return nil, ErrNotFound
	}

	return s.openMedia(ctx, key)
}

// openMedia reads an object from storage and derives its response content type.
func (s *service) openMedia(
	ctx context.Context,
	key string,
) (*MediaFile, error) {

	reader, err := s.storage.Open(ctx, key)
	if err != nil {
		if errors.Is(err, storage.ErrFileNotFound) {
			return nil, ErrNotFound
		}

		return nil, err
	}

	return &MediaFile{
		Content:     reader,
		ContentType: mediaContentType(key),
	}, nil
}

// cleanMediaPath accepts only non-empty relative paths made of ordinary
// path segments. Media keys are generated by the worker, so traversal
// segments are never valid.
func cleanMediaPath(raw string) (string, bool) {
	raw = strings.TrimPrefix(raw, "/")

	if raw == "" ||
		strings.ContainsRune(raw, '\\') ||
		strings.ContainsRune(raw, 0) {
		return "", false
	}

	for _, segment := range strings.Split(raw, "/") {
		if segment == "" || segment == "." || segment == ".." {
			return "", false
		}
	}

	return raw, true
}

// mediaContentType returns the response content type for a stored key.
func mediaContentType(key string) string {
	switch strings.ToLower(path.Ext(key)) {
	case ".m3u8":
		return "application/vnd.apple.mpegurl"
	case ".ts":
		return "video/mp2t"
	case ".m4s":
		return "video/iso.segment"
	case ".jpg", ".jpeg":
		return "image/jpeg"
	case ".png":
		return "image/png"
	case ".vtt":
		return "text/vtt"
	default:
		return "application/octet-stream"
	}
}
